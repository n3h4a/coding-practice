#!/usr/bin/env python3
"""Rebuilds the problem index in README.md.

Every solution starts with a header comment like:

    /*
     * Two Sum
     * Pattern : Hashing
     * Approach: ...
     * Time    : O(n)
     * Space   : O(n)
     */

Title, link and difficulty come from the folder's README.md. The script groups
problems by pattern and rewrites everything between the PROBLEMS markers in
the root README.md.

Usage:
    python3 scripts/generate_readme.py          # rewrite README.md
    python3 scripts/generate_readme.py --check  # fail if README.md is stale
"""

import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
START, END = "<!-- PROBLEMS:START -->", "<!-- PROBLEMS:END -->"

# First part of a "Pattern" line -> section in the README (in display order).
CATEGORIES = {
    "Arrays & Simulation": ["Array", "Array Simulation"],
    "Hashing & Counting": ["Hashing", "Counting"],
    "Two Pointers": ["Two Pointers", "Fast & Slow Pointers"],
    "Sliding Window": ["Sliding Window"],
    "Binary Search": ["Binary Search", "Binary Search on Answer"],
    "Prefix Sum & Difference Array": ["Prefix Sum", "Difference Array"],
    "Cyclic Sort": ["Cyclic Sort"],
    "Matrix": ["Matrix"],
    "Stack": ["Stack"],
    "Trees": ["Tree DFS"],
    "Dynamic Programming & Classic Algorithms": [
        "Dynamic Programming",
        "Kadane's Algorithm",
        "Boyer-Moore Voting",
    ],
    "Strings & Sorting": ["Strings"],
    "Math": ["Math"],
}
CATEGORY_OF = {key: cat for cat, keys in CATEGORIES.items() for key in keys}
DIFFICULTY_ORDER = {"Easy": 0, "Medium": 1, "Hard": 2}
BADGE = {"Easy": "🟢 Easy", "Medium": "🟠 Medium", "Hard": "🔴 Hard"}


def header_field(source: str, name: str) -> str:
    match = re.search(rf"^\s*\*\s*{name}\s*:\s*(.+)$", source, re.M)
    if not match:
        raise ValueError(f"missing '{name}:' in header")
    return match.group(1).strip()


def load_problem(folder: Path) -> dict:
    solutions = sorted(folder.glob("*.java"))
    if not solutions:
        raise ValueError("no .java solution")
    source = solutions[0].read_text(encoding="utf-8")
    statement = (folder / "README.md").read_text(encoding="utf-8")

    title = re.search(r'<h2><a href="([^"]+)">(.+?)</a></h2>', statement)
    difficulty = re.search(r"Difficulty-(Easy|Medium|Hard)", statement)
    if not title or not difficulty:
        raise ValueError("could not read title/difficulty from README.md")

    pattern = header_field(source, "Pattern")
    key = re.split(r" / | \+ | \(", pattern)[0].strip()
    if key not in CATEGORY_OF:
        raise ValueError(f"unknown pattern '{key}' - add it to CATEGORIES")

    return {
        "folder": folder.name,
        "solution": solutions[0].name,
        "url": title.group(1),
        "title": title.group(2),
        "difficulty": difficulty.group(1),
        "pattern": pattern,
        "category": CATEGORY_OF[key],
        "time": header_field(source, "Time"),
        "space": header_field(source, "Space"),
    }


CATEGORY_ICON = {
    "Arrays & Simulation": "🧱",
    "Hashing & Counting": "#️⃣",
    "Two Pointers": "👉",
    "Sliding Window": "🪟",
    "Binary Search": "🔍",
    "Prefix Sum & Difference Array": "📈",
    "Cyclic Sort": "🔄",
    "Matrix": "🔢",
    "Stack": "📚",
    "Trees": "🌳",
    "Dynamic Programming & Classic Algorithms": "🧠",
    "Strings & Sorting": "🔤",
    "Math": "➗",
}


def render(problems: list) -> str:
    by_category = defaultdict(list)
    for p in problems:
        by_category[p["category"]].append(p)
    counts = Counter(p["difficulty"] for p in problems)
    sections = [c for c in CATEGORIES if by_category[c]]

    out = [
        START,
        "<!-- Generated by scripts/generate_readme.py - do not edit by hand. -->",
        "",
        "<a id=\"at-a-glance\"></a>",
        "",
        "## 📊 At a Glance",
        "",
        "<div align=\"center\">",
        "",
        "| 🧩 Total | 🟢 Easy | 🟠 Medium | 🔴 Hard | 🗂️ Patterns |",
        "|:---:|:---:|:---:|:---:|:---:|",
        f"| **{len(problems)}** | **{counts['Easy']}** | **{counts['Medium']}** "
        f"| **{counts['Hard']}** | **{len(sections)}** |",
        "",
        "</div>",
        "",
        "```mermaid",
        "pie showData",
        "    title Problems by pattern",
    ]
    for c in sorted(sections, key=lambda c: -len(by_category[c])):
        out.append(f'    "{c.replace("&", "and")}" : {len(by_category[c])}')
    out += ["```", "", "<a id=\"problems\"></a>", "", "## 🗂️ Problems by Pattern", "",
            "> Click a pattern to expand it. Every row links to the problem on LeetCode "
            "and to my solution.", ""]

    for category in sections:
        rows = sorted(
            by_category[category],
            key=lambda p: (DIFFICULTY_ORDER[p["difficulty"]], p["title"].lower()),
        )
        mix = Counter(p["difficulty"] for p in rows)
        mix_text = " · ".join(
            f"{BADGE[d].split()[0]} {mix[d]}" for d in DIFFICULTY_ORDER if mix[d]
        )
        out += [
            "<details>",
            f"<summary><b>{CATEGORY_ICON[category]} {category}</b> "
            f"&nbsp;—&nbsp; {len(rows)} problem{'s' if len(rows) != 1 else ''} "
            f"&nbsp;({mix_text})</summary>",
            "",
            "| # | Problem | Difficulty | Technique | Time | Space | Code |",
            "|:---:|---|---|---|---|---|:---:|",
        ]
        for i, p in enumerate(rows, 1):
            out.append(
                f"| {i} | [{p['title']}]({p['url']}) | {BADGE[p['difficulty']]} | {p['pattern']} "
                f"| {cell(p['time'])} | {cell(p['space'])} "
                f"| [☕ Java](./{p['folder']}/{p['solution']}) |"
            )
        out += ["", "</details>", ""]

    out.append(END)
    return "\n".join(out)


def update_badges(text: str, problems: list) -> str:
    """Keeps the shields.io count badges in the intro in sync."""
    counts = Counter(p["difficulty"] for p in problems)
    text = re.sub(r"badge/problems-\d+", f"badge/problems-{len(problems)}", text)
    for level in DIFFICULTY_ORDER:
        text = re.sub(rf"badge/{level}-\d+", f"badge/{level}-{counts[level]}", text)
    return text


def cell(text: str) -> str:
    """Keeps only the complexity itself (drops the trailing explanation)."""
    text = re.split(r" - | \(|, | for | extra| API| recursion", text)[0].strip()
    return f"`{text}`"


def anchor(heading: str) -> str:
    slug = heading.lower().replace(" ", "-")
    return re.sub(r"[^a-z0-9\-]", "", slug)


def main() -> int:
    problems, errors = [], []
    for folder in sorted(ROOT.iterdir()):
        if not folder.is_dir() or not (folder / "README.md").exists():
            continue
        if not re.match(r"^\d+-", folder.name):
            continue
        try:
            problems.append(load_problem(folder))
        except ValueError as err:
            errors.append(f"{folder.name}: {err}")

    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1

    current = README.read_text(encoding="utf-8")
    if START not in current or END not in current:
        print(f"README.md must contain {START} and {END}", file=sys.stderr)
        return 1
    before = current.split(START)[0]
    after = current.split(END)[1]
    updated = update_badges(before, problems) + render(problems) + after

    if "--check" in sys.argv:
        if updated != current:
            print("README.md is out of date - run: python3 scripts/generate_readme.py",
                  file=sys.stderr)
            return 1
        print(f"README.md is up to date ({len(problems)} problems).")
        return 0

    README.write_text(updated, encoding="utf-8")
    print(f"README.md updated with {len(problems)} problems.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
